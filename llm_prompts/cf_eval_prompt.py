import re

from llm_prompts.prompt_manager import PromptManager


class CFEvalPromptManager(PromptManager):
    """
    Prompt for counterfactual explanations as proposed in https://ojs.aaai.org/index.php/AAAI/article/view/33791.
    """
    properties = ["satisfaction", "feasibility", "consistency", "completeness", "trust", "understandability",
                  "fairness", "complexity"]
    prop_definitions = {
        "satisfaction": "this scenario effectively explains how to reach a different outcome",
        "feasibility": "the actions suggested by the explanation are practical, realistic to implement and actionable",
        "consistency": "the parts of the explanation do not contradict each other",
        "completeness": "the explanation is sufficient in explaining how to achieve the desired outcome",
        "trust": "I believe that the suggested changes would bring about the desired outcome",
        "understandability": "I feel like I understood the phrasing of the explanation well",
        "fairness": "the explanation is unbiased towards different user groups and does not operate on sensitive "
                    "features",
        "complexity": "the explanation has an appropriate level of detail and complexity - not too simple, yet not "
                      "overly complex"
    }
    prop_adjectives = {
        "satisfaction": "satisfying",
        "feasibility": "feasible",
        "consistency": "consistent",
        "completeness": "complete",
        "trust": "trustworthy",
        "understandability": "understandable",
        "fairness": "fair",
        "complexity": "complex"
    }

    def __init__(self, property_name: str, prompt_style: str = 'base', examples: list = None):
        super().__init__()
        assert property_name in self.prop_definitions, f"Property must be one of {self.properties}."
        assert prompt_style in ['base', 'full'], "Prompt style must be one of base or full."
        if prompt_style == 'base':
            examples = None
        self.property_name = property_name
        self.prompt_style = prompt_style
        self.examples = examples
        # self.answer_prompt = (f"Please rate as 'low', 'medium' or 'high', how {self.prop_adjectives[property_name]} "
        #                       f"is this explanation: ")
        self.answer_prompt = f"{self.prop_adjectives[property_name].capitalize()} rating (low, medium or high):"

    def get_system_prompt(self) -> dict[str, str]:
        # base_prompt = (
        #     "You are evaluating counterfactual explanations generated by AI. Counterfactual explanations explain "
        #     "what parameters of a situation should have been different for the outcome to have been different. "
        #     "You are not expected to provide reasoning or explanation and should answer with the appropriate value "
        #     "from the set ['low', 'medium', 'high']. "
        # )
        base_prompt = (
            "You are an automated evaluation system for AI-generated counterfactual explanations. "
            "Counterfactual explanations explain what parameters of a situation should have been different for the "
            "outcome to have been different.\n"
            "CRITICAL INSTRUCTIONS:\n"
            "1. You MUST output exactly one word from this exact set: ['low', 'medium', 'high'].\n"
            "2. Providing reasoning, explanations, or conversational filler is STRICTLY FORBIDDEN.\n"
            "3. Do not include any punctuation in your final answer.\n"
        )

        if self.prompt_style == 'base':
            base_prompt += f"Definition of {self.property_name}: {self.prop_definitions[self.property_name]}. "

        elif self.prompt_style == 'full':
            for prop, prop_def in self.prop_definitions.items():
                base_prompt += f"The definition of {prop}: {prop_def}. "

        else:
            raise ValueError("Prompt style '{}' not recognized".format(self.prompt_style))

        example_prompt = ''
        if self.examples is not None:
            example_prompt = f"Here are {len(self.examples)} examples of a prompt and the output.\n"
            for ix, example in enumerate(self.examples, 1):
                cf = example['cf']
                label = example['label']
                example_prompt += f"Example prompt {ix}: {cf} "
                example_prompt += f"Example output {ix}: {label}. "
            example_prompt += "Please answer questions in a similar format. "

        final_prompt = base_prompt + example_prompt
        # final_prompt += "The following is the counterfactual explanation."

        return {
            "role": "system",
            "content": final_prompt
        }

    def get_user_prompt_content(self, cf: str) -> str:
        # user_prompt = f"\"{cf}\" {self.answer_prompt}"
        user_prompt = f"{cf}\n\n{self.answer_prompt}"
        return user_prompt

    def parse_response(self, response: str) -> str:
        """
        Parse the LLM's response into a structured format.
        """
        response = re.findall(r"[a-zA-Z]+", response)
        assert len(response) > 0  # should be a list with 1 element
        response = response[0].lower()
        response = response.strip()
        assert response in ["low", "medium", "high"]

        return response
